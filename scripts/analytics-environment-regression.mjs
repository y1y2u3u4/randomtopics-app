import assert from 'node:assert/strict';
import { load } from './lib/load-typescript.mjs';
const sent = [], local = [], storage = new Map();
globalThis.sessionStorage = { getItem: k => storage.get(k), setItem: (k,v) => storage.set(k,v), removeItem: k => storage.delete(k) };
globalThis.document = { title: 'Fixture', documentElement: { lang: 'en' } };
globalThis.CustomEvent = class { constructor(type, options) { this.type=type; this.detail=options.detail; } };
globalThis.window = { location: { hostname:'localhost', pathname:'/speech', origin:'http://localhost', search:'' }, sessionStorage, localStorage: sessionStorage, gtag:(...args)=>sent.push(args), dispatchEvent:e=>local.push(e.detail) };
const {track} = load('src/lib/track.ts', {'./coreUsage':{coreUsageEvents:()=>[]}});
track('speech_feedback_ready', {is_test:false,environment:'production'});
assert.equal(sent.length,0);
assert.equal(local[0].params.is_test,true);
assert.equal(local[0].params.environment,'local_preview');
window.location.hostname='randomtopics.app';
window.location.origin='https://randomtopics.app';
track('speech_feedback_view');
assert.equal(sent.at(-1)[2].is_test,false);
assert.equal(sent.at(-1)[2].environment,'production');
track('qa_speech_feedback_view');
assert.equal(sent.at(-1)[1],'qa_speech_feedback_view');
assert.equal(sent.at(-1)[2].is_test,true);
window.location.search='?usage_qa=1';
track('speech_checkout_redirect');
assert.equal(sent.at(-1)[1],'qa_speech_checkout_redirect');
assert.equal(sent.at(-1)[2].is_test,true);
window.location.pathname='/internal/analytics';
const count=sent.length;
track('speech_feedback_view');
assert.equal(sent.length,count);
assert.ok(sent.every(e=>e[2].schema_version==='1'));
console.log('PASS: local-only preview, authoritative QA/environment fields, existing names, internal exclusion (mock transport only).');
