import assert from 'node:assert/strict';
import { coreUsageEvents } from '../src/lib/coreUsage.ts';
import { coreUsageRows } from '../src/lib/coreUsageReport.ts';
const store = () => { const data = new Map(); return { data, getItem:k=>data.get(k)??null, setItem:(k,v)=>data.set(k,v), removeItem:k=>data.delete(k) }; };
const local=store(), session=store();
let now=1_800_000_000_000;
const run=(event,params={},path='/question-of-the-day',qa=false)=>coreUsageEvents(path,event,params,local,session,now,qa);
assert.deepEqual(run('page_view'),['qotd_usage_visit']);
assert.deepEqual(run('copy_error',{action_surface:'qotd_daily'}),['qotd_daily_copy_error']);
now+=31*60_000;assert.deepEqual(run('page_view'),['qotd_usage_visit'],'failed copy is not use');
for(const source of ['daily','random','list']) assert.deepEqual(run('copy_result',{action_surface:`qotd_${source}`}),[`qotd_${source}_copy`]);
assert.deepEqual(run('page_view'),['qotd_usage_visit'],'reload is not return');
now+=31*60_000;assert.deepEqual(run('page_view'),['qotd_usage_visit','qotd_return_after_use']);
assert.deepEqual(run('page_view'),['qotd_usage_visit'],'duplicate view does not duplicate return');
now+=31*60_000;assert.deepEqual(run('page_view',{},'/question-of-the-day',true),['qotd_usage_visit'],'QA never consumes natural markers');
now+=31*24*60*60_000;assert.deepEqual(run('page_view'),['qotd_usage_visit'],'expired use does not qualify');
const broken={getItem(){throw Error('blocked')},setItem(){throw Error('blocked')},removeItem(){throw Error('blocked')}};
assert.deepEqual(coreUsageEvents('/question-of-the-day','copy_result',{action_surface:'qotd_list'},broken,broken,now),['qotd_list_copy']);
const speech='/speech';
assert.deepEqual(run('speech_feedback_v5_request',{},speech),[]);
run('timer_complete',{},speech);
assert.deepEqual(run('speech_feedback_v5_request',{},speech),['speech_after_timer_feedback_request']);
assert.deepEqual(run('speech_feedback_v5_request',{},speech),[],'consume once per completion');
run('timer_complete',{},speech);now+=31*60_000;
assert.deepEqual(run('speech_feedback_v5_request',{},speech),[],'expired timer not correlated');
const article='/es/topics/most-likely-to-questions', p={content_source:'es_most_likely_article'};
run('generate_success',p,article);
assert.deepEqual(run('party_article_to_tool',p,article),['party_tool_entry_with_unfinished']);
assert.ok(run('page_view',{},article).includes('party_revisit_unfinished'));
run('party_round_complete',p,article);
assert.ok(!run('page_view',{},article).includes('party_revisit_unfinished'));
assert.deepEqual(run('copy_result',{action_surface:'party_round_collection'},article),['party_round_copy']);
assert.deepEqual(run('copy_result',{action_surface:'party_round_question'},article),[]);
assert.equal(JSON.stringify([...local.data,...session.data]).includes('question text'),false);
const rows=coreUsageRows([['current7','2026-09-22','2026-09-28','/question-of-the-day','qa_qotd_list_copy',10,4]],'current7','2026-09-22','2026-09-28');
assert.ok(rows.every(r=>r[5]===0&&r[6]===0),'QA names excluded from natural report');
assert.ok(coreUsageRows([],'current7','2026-09-13','2026-09-19').every(r=>r[7]==='before_release_no_new_signal'));
assert.ok(coreUsageRows([],'current7','2026-09-22','2026-09-28',true).every(r=>r[7]==='limited_report'));
console.log('PASS: source-specific success/error, return inactivity and expiry, QA isolation, timer order, unfinished-round markers and report coverage.');
