// Scans public/nba/players/*.jpg and writes src/data/nbaPortraits.ts (ids that have a portrait).
// Run: node scripts/nba-portraits.mjs   (after adding or removing portrait files)
import { readdirSync, existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const dir = resolve(root, "public/nba/players");
const ids = existsSync(dir)
  ? readdirSync(dir).filter((f) => /^[a-z0-9-]+\.jpg$/.test(f)).map((f) => f.slice(0, -4)).sort()
  : [];
const body = ids.length ? `\n${ids.map((i) => `  "${i}",`).join("\n")}\n` : "";
writeFileSync(
  resolve(root, "src/data/nbaPortraits.ts"),
  `// GENERATED by scripts/nba-portraits.mjs from public/nba/players/*.jpg. Do not edit by hand.\n// Original illustrated fan art, 384px square, one file per player id.\nexport const NBA_PORTRAIT_IDS: readonly string[] = [${body}];\n`,
);
console.log(`nba portraits: ${ids.length} found`);
