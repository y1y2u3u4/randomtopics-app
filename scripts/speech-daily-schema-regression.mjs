import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { load } from './lib/load-typescript.mjs';
const { SPEECH_DAILY_HEADERS: headers, SPEECH_DAILY_SCHEMA: schema, planSpeechDailyWrite: plan, readSpeechDailyRow: read } = load('src/lib/speech/dailySchema.ts');
const metrics = [{eventName:'speech_checkout_request',eventCount:2,totalUsers:1},{eventName:'speech_feedback_ready',eventCount:12,totalUsers:8}];
const date = '2026-10-04', names = metrics.map(m=>m.eventName);
const first = plan([],date,names,metrics);
assert.deepEqual(first.ranges[0].values,[headers]);
assert.equal(first.requiredRows,3);
const existing = [headers,...first.ranges[1].values];
const frozen = structuredClone(existing);
const reordered = plan(existing,date,[names[1],names[0]],metrics);
assert.deepEqual(reordered.ranges,[{range:"'Speech Daily v2'!A2",values:existing.slice(1)}], 'Reordering the source cannot reorder historical metrics');
assert.deepEqual(existing,frozen);
const added = plan(existing,date,['speech_new_event',...names],metrics);
assert.equal(added.requiredRows,4);
assert.deepEqual(added.ranges[0].values.slice(0,2),existing.slice(1));
assert.deepEqual(added.ranges[0].values[2],[date,schema,'speech_new_event',0,0,'independent-events']);
const next = plan(existing,'2026-10-05',names,metrics);
assert.equal(next.ranges[0].range,"'Speech Daily v2'!A4");
assert.deepEqual(existing,frozen,'New date preserves historical records');
assert.throws(()=>plan([['Report date','legacy',...Array(552).fill('new-header')],['2026-09-20',...Array(143).fill(1)]],date,names,metrics),/schema_unknown/);
assert.deepEqual(read(['2026-09-20','speech-v2',...Array(142).fill(1)]),{status:'unknown_schema_or_values'},'A 144-column legacy row cannot become a checkout conversion under the 554-column header');
assert.throws(()=>plan([headers,...existing.slice(1),existing[1]],date,names,metrics),/duplicate_key/);
assert.throws(()=>plan([headers,[date,schema,names[0],'',1]],date,names,metrics),/row_unknown/,'Missing count is unknown, not zero');
assert.throws(()=>plan(existing,date,names,[{...metrics[0],eventCount:NaN}]),/metric_invalid/);
assert.equal(read(existing[1]).eventName,'speech_checkout_request');
assert.equal(read(existing[1]).eventCount,2);
// Regression (2026-10-06 → 10-11): formatted reads return numbers as strings,
// which made every existing row unknown and failed the whole daily sync.
assert.throws(()=>plan([headers,[date,schema,names[0],'23','19']],'2026-10-05',names,metrics),/row_unknown/,'Display-text counts are not trusted as numbers');
const sheetSource = readFileSync(new URL('../src/lib/analyticsSheet.ts', import.meta.url), 'utf8');
assert.match(sheetSource,/SPEECH_DAILY_TAB\}'!A1:F\$\{speechGrid\.rowCount\}`, "UNFORMATTED_VALUE"\)/,'Speech Daily rows must be read unformatted');
assert.match(sheetSource,/valueRenderOption=\$\{render\}/,'getValues passes the render option to the API');
console.log('PASS Speech Daily schema: fixed named rows, retry upsert, event reordering/addition, historical preservation, duplicate/unknown/missing values fail closed.');
