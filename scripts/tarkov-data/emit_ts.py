import json, sys
d = json.load(open(sys.argv[1]))
out = sys.argv[2]
W = d['weapons']; A = d['ammo']
lines = []
lines.append('// Escape from Tarkov weapon + ammo data for /tarkov-random-weapon-generator.')
lines.append('// Generated by scripts/tarkov-data/build.py from the community Escape from Tarkov Wiki:')
lines.append('//   "Weapons" page revision 2026-10-08, "Ballistics" page revision 2026-10-26, fetched 2026-11-15.')
lines.append('// Weapon renders in /public/tarkov/weapons are © Battlestate Games, mirrored for identification only.')
lines.append('// Do not edit by hand; re-run the build script after a game patch.')
lines.append('')
lines.append('export const TARKOV_DATA_DATE = "2026-11-15";')
lines.append('export const TARKOV_WIKI_REVISIONS = { weapons: "2026-10-08", ballistics: "2026-10-26" } as const;')
lines.append('')
lines.append('export type WeaponClass = "ar" | "carbine" | "smg" | "shotgun" | "dmr" | "bolt" | "lmg" | "gl" | "pistol" | "revolver" | "melee";')
lines.append('')
lines.append('/** [id, name, class, caliber, fire modes, rate of fire] — melee has empty caliber/modes and rof 0. */')
lines.append('export type WeaponRow = readonly [string, string, WeaponClass, string, string, number];')
lines.append('')
lines.append('export const WEAPON_ROWS: readonly WeaponRow[] = [')
for w in W:
    row = [w['id'], w['name'], w['cls'], w.get('caliber') or '', w.get('modes') or '', w.get('rof') or 0]
    lines.append('  ' + json.dumps(row, ensure_ascii=False) + ',')
lines.append('];')
lines.append('')
lines.append('/** [caliber, name, damage per projectile, penetration, pellets (0 = single projectile), flags: t = tracer, s = subsonic] */')
lines.append('export type AmmoRow = readonly [string, string, number, number, number, string];')
lines.append('')
lines.append('export const AMMO_ROWS: readonly AmmoRow[] = [')
for a in A:
    flags = ('t' if a['tracer'] else '') + ('s' if a['subsonic'] else '')
    row = [a['caliber'], a['name'], a['dmg'] or 0, a['pen'] or 0, a['pellets'] or 0, flags]
    lines.append('  ' + json.dumps(row, ensure_ascii=False) + ',')
lines.append('];')
open(out, 'w').write('\n'.join(lines) + '\n')
print('ok', len(W), len(A))
