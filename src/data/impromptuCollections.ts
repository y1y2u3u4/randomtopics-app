export function impromptuTopics(c: ImpromptuCollection): string[] {
  return c.groups.flatMap((g) => g.topics);
}

export function getImpromptuCollection(slug: ImpromptuCollection["slug"]): ImpromptuCollection {
  return IMPROMPTU_COLLECTIONS.find((c) => c.slug === slug)!;
}
