export function splitWyr(pair: string): [string, string] {
  const [a, b] = pair.split(" | ");
  return [a, b];
}

export function wyrText(pair: string): string {
  const [a, b] = splitWyr(pair);
  return `Would you rather ${a} or ${b}?`;
}
