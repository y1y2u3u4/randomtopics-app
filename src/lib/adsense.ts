const AUTO_AD_PATHS: ReadonlySet<string> = new Set(AD_PUBLIC_PATHS);

/** Pages that render the manual in-content unit (reviewed + result lists). */
export function adInlinePageAllowed(path: string) {
  return ADSENSE_PUBLIC_PATHS.some(allowed => allowed === path) || ADSENSE_RESULT_PATHS.some(allowed => allowed === path);
}

/** Pages whose document may load the AdSense runtime at all. */
export function adPageAllowed(path: string) {
  return adInlinePageAllowed(path) || AUTO_AD_PATHS.has(path);
}

export function adConfiguration(mode: string | undefined, slot: string | undefined = ADSENSE_ARTICLE_SLOT) {
  // Keep the existing rollout flag and manual unit ID. Account-level Auto ads
  // share this gated SDK and published CMP; a publisher ID is not a slot ID.
  return mode === "manual-public-reviewed-v1" && /^\d{6,20}$/.test(slot ?? "")
    ? { slot: slot! } : null;
}

// Campaign tags only (e.g. ?utm_source=chatgpt.com from AI-assistant links,
// ~240 documents a week in Oct 2026). Any other query, including rt_ads=off,
// still fails closed.
const CAMPAIGN_PARAM = /^utm_(source|medium|campaign|term|content)$/;
function campaignOnlySearch(search: string) {
  if (!search) return true;
  const keys = [...new URLSearchParams(search).keys()];
  return keys.length > 0 && keys.length <= 5 && keys.every((key) => CAMPAIGN_PARAM.test(key));
}

export function adRequestAllowed(options: {
  path: string; host: string; search: string; qa: boolean; globalPrivacyControl: boolean;
}) {
  return adPageAllowed(options.path) &&
    ["randomtopics.app", "www.randomtopics.app"].includes(options.host) &&
    campaignOnlySearch(options.search) && !options.qa && !options.globalPrivacyControl;
}

// Personalized ads only where the visitor has not refused them: the published
// Google message (TCF) decides in the EEA, UK and Switzerland, and a US state
// opt-out or GPC stops advertising entirely (see adsenseClient). Child- and
// classroom-directed paths always stay non-personalized with restricted data
// processing, even if one is ever added to the ad page lists.
const CHILD_DIRECTED = [/(^|\/|-)kids(\/|-|$)/, /students?(\/|$)/, /middle-school/, /presentation-ideas-for-school/,
  /^(\/es)?\/(classroom|morning-meeting-questions|riddles-for-kids|random-group-generator)/];
export function adPersonalizationAllowed(path: string) {
  return !CHILD_DIRECTED.some((pattern) => pattern.test(path));
}

export function adDocumentBoundary(previousPath: string, nextPath: string) {
  // AdSense has no supported SPA teardown. A fresh document also prevents a
  // later visit to private practice from inheriting a public-page ad runtime.
  return previousPath !== nextPath && (adPageAllowed(previousPath) || adPageAllowed(nextPath));
}

// A deny-only marker: the existing no-query policy excludes the next document
// before either CMP or AdSense can start. It never grants paid access.
export function adRetirementUrl(href: string) {
  const url = new URL(href);
  url.searchParams.set("rt_ads", "off");
  return url.href;
}
