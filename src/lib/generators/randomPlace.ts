export const PLACES: Place[] = (Object.keys(RAW) as PlaceCategory[]).flatMap((category) =>
  RAW[category].split("\n").map((row) => {
    const [name, line, mood] = row.split(" | ");
    return { name, line, category, mood: mood as PlaceMood };
  }),
);

