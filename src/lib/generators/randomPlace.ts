export const placeGenerator = listGenerator<Place>({
  items: PLACES,
  key: (p) => p.name,
  facets: { category: (p) => [p.category], mood: (p) => [p.mood] },
  toResult: (p) => ({
    key: p.name,
    title: p.name,
    subtitle: `${PLACE_CATEGORIES.find((c) => c.id === p.category)!.short} · ${p.mood}`,
    detail: `${p.line}.`,
  }),
});
