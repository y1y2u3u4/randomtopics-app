export const THEMES: Theme[] = (Object.entries(BANK) as [ThemeUse, Row[]][]).flatMap(([use, rows]) =>
  rows.map(([name, mood, idea], i) => ({ id: `${use}-${i + 1}`, name, use, mood: M[mood], idea })),
);

export const themeFilters: FilterGroup[] = [
  { id: "use", label: "Use", multi: true, options: THEME_USES.map((u) => ({ value: u.id, label: `${u.emoji} ${u.label}` })) },
  { id: "mood", label: "Mood", multi: true, options: THEME_MOODS.map((m) => ({ value: m.id, label: m.label })) },
];

const USE_LABEL = Object.fromEntries(THEME_USES.map((u) => [u.id, u]));

export const themeGenerator = listGenerator<Theme>({
  items: THEMES,
  key: (t) => t.id,
  facets: { use: (t) => [t.use], mood: (t) => [t.mood] },
  toResult: (t) => ({
    key: t.id,
    title: t.name,
    subtitle: `${USE_LABEL[t.use].label} · ${t.mood}`,
    detail: t.idea,
    emoji: USE_LABEL[t.use].emoji,
  }),
});
